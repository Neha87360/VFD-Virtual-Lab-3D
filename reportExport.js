/**
 * reportExport.js
 * Handles CSV export of observation data and multi-section PDF laboratory report
 * generation using jsPDF (bundled locally in lib/jspdf.umd.min.js).
 */

(function (global) {
  'use strict';

  function triggerDownload(blob, filename) {
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  }

  function escapeCsvCell(value) {
    const str = String(value ?? '');
    if (/[",\n]/.test(str)) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  }

  /**
   * Exports all recorded observations as a clean CSV file.
   * @param {Array} observations
   */
  function exportObservationsCSV(observations) {
    if (!observations || !observations.length) {
      return false;
    }

    const lines = [
      '# BREAKDOWN VOLTAGE TESTING OF TRANSFORMER OIL USING A VIRTUAL SPHERE GAP',
      '# NOTE: Simulated educational dataset generated by Virtual HV Laboratory (not real physical test data).',
      `# Exported: ${new Date().toISOString()}`,
      ['Trial No.', 'Oil Condition', 'Gap Distance (mm)', 'Breakdown Voltage (kV)', 'Dielectric Strength (kV/mm)']
        .map(escapeCsvCell)
        .join(',')
    ];

    observations.forEach((row) => {
      lines.push(
        [
          row.trialNo,
          row.oilName,
          row.gapMm.toFixed(1),
          row.breakdownKv.toFixed(1),
          row.dielectricStrength.toFixed(2)
        ]
          .map(escapeCsvCell)
          .join(',')
      );
    });

    const blob = new Blob([lines.join('\r\n')], { type: 'text/csv;charset=utf-8;' });
    triggerDownload(blob, 'transformer_oil_bdv_observations.csv');
    return true;
  }

  /**
   * Exports a formatted engineering experiment report as PDF.
   * @param {{observations: Array, conclusionSummary: string, chartImages: object}} payload
   */
  function exportReportPDF({ observations, conclusionSummary, chartImages }) {
    const jspdfNs = global.jspdf;
    if (!jspdfNs || !jspdfNs.jsPDF) {
      global.print();
      return;
    }

    const { jsPDF } = jspdfNs;
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
    const pageW = doc.internal.pageSize.getWidth();
    const pageH = doc.internal.pageSize.getHeight();
    const margin = 15;
    const contentW = pageW - margin * 2;
    let y = 16;

    const checkPageBreak = (neededHeight) => {
      if (y + neededHeight > pageH - 16) {
        doc.addPage();
        y = 18;
      }
    };

    // Header Banner
    doc.setFillColor(11, 19, 36);
    doc.rect(0, 0, pageW, 34, 'F');
    doc.setFillColor(2, 132, 199);
    doc.rect(0, 32, pageW, 2.5, 'F');

    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13.5);
    doc.text('BREAKDOWN VOLTAGE TESTING OF TRANSFORMER OIL', margin, 14);
    doc.text('USING A VIRTUAL SPHERE GAP', margin, 21);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    doc.setTextColor(147, 197, 253);
    doc.text(`Virtual High-Voltage Engineering Laboratory Report  |  Generated: ${new Date().toLocaleString()}`, margin, 28);

    y = 42;

    // Simulation Notice Box
    doc.setFillColor(239, 246, 255);
    doc.setDrawColor(59, 130, 246);
    doc.roundedRect(margin, y, contentW, 18, 2, 2, 'FD');
    doc.setTextColor(30, 58, 138);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.text('EDUCATIONAL SIMULATION NOTICE', margin + 4, y + 6);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8.2);
    const noticeLines = doc.splitTextToSize(
      'All values in this report are generated by an educational simulation model with configurable thresholds. ' +
      'Dielectric Strength is simplified as E = Breakdown Voltage / Electrode Gap (kV/mm); real-world testing ' +
      'depends on applicable standards (IEC 60156 / ASTM D877 / D1816) and sphere/electrode geometry.',
      contentW - 8
    );
    doc.text(noticeLines, margin + 4, y + 11);
    y += 25;

    // Observation Table Section
    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11.5);
    doc.text('1. Simulated Observation Table', margin, y);
    y += 5;

    const colWidths = [20, 48, 36, 40, 36];
    const headers = ['Trial No.', 'Oil Condition', 'Gap (mm)', 'BDV (kV)', 'Strength (kV/mm)'];

    const drawTableHeader = () => {
      doc.setFillColor(15, 27, 51);
      doc.rect(margin, y, contentW, 8, 'F');
      doc.setTextColor(255, 255, 255);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8.5);
      let x = margin + 3;
      headers.forEach((h, i) => {
        doc.text(h, x, y + 5.5);
        x += colWidths[i];
      });
      y += 8;
    };

    drawTableHeader();

    if (!observations || !observations.length) {
      doc.setFillColor(248, 250, 252);
      doc.rect(margin, y, contentW, 9, 'F');
      doc.setTextColor(100, 116, 139);
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(8.5);
      doc.text('No simulated observations recorded in this session.', margin + 4, y + 6);
      y += 14;
    } else {
      observations.forEach((obs, idx) => {
        checkPageBreak(10);
        if (y < 22) drawTableHeader();

        doc.setFillColor(idx % 2 === 0 ? 255 : 248, idx % 2 === 0 ? 255 : 250, idx % 2 === 0 ? 255 : 252);
        doc.setDrawColor(226, 232, 240);
        doc.rect(margin, y, contentW, 7.5, 'FD');

        doc.setTextColor(30, 41, 59);
        doc.setFont('helvetica', 'normal');
        doc.setFontSize(8.5);

        const cells = [
          String(obs.trialNo),
          obs.oilName,
          obs.gapMm.toFixed(1),
          obs.breakdownKv.toFixed(1),
          obs.dielectricStrength.toFixed(2)
        ];
        let x = margin + 3;
        cells.forEach((val, i) => {
          doc.text(val, x, y + 5.2);
          x += colWidths[i];
        });
        y += 7.5;
      });
      y += 7;
    }

    // Result and Conclusion Section
    checkPageBreak(38);
    doc.setTextColor(15, 23, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11.5);
    doc.text('2. Result & Engineering Conclusion', margin, y);
    y += 6;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.2);
    doc.setTextColor(51, 65, 85);
    const cleanSummary = (conclusionSummary || '').replace(/\s+/g, ' ').trim();
    const summaryLines = doc.splitTextToSize(cleanSummary, contentW);
    summaryLines.forEach((line) => {
      checkPageBreak(6);
      doc.text(line, margin, y);
      y += 5;
    });

    y += 4;
    checkPageBreak(26);
    const moistureNote = doc.splitTextToSize(
      'Engineering Principle: Moisture, dissolved gases, cellulose fibers, and carbonized impurities drastically ' +
      'reduce the dielectric strength of transformer oil. Under high electric fields, polar water droplets and ' +
      'suspended particles align along electric field lines to form low-resistance conductive bridges across the ' +
      'sphere gap, initiating premature streamer propagation and electrical breakdown.',
      contentW
    );
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(71, 85, 105);
    moistureNote.forEach((line) => {
      checkPageBreak(6);
      doc.text(line, margin, y);
      y += 5;
    });

    // Graphical Analysis Snapshots
    if (chartImages && (chartImages.bdvGap || chartImages.bdvOil)) {
      doc.addPage();
      y = 18;
      doc.setTextColor(15, 23, 42);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11.5);
      doc.text('3. Graphical Analysis (Simulated Plots)', margin, y);
      y += 7;

      const addChartImg = (title, imgData) => {
        if (!imgData) return;
        checkPageBreak(78);
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(9.5);
        doc.setTextColor(30, 58, 138);
        doc.text(title, margin, y);
        y += 3;
        doc.addImage(imgData, 'PNG', margin, y, contentW, 66);
        y += 72;
      };

      addChartImg('Breakdown Voltage vs Gap Distance', chartImages.bdvGap);
      addChartImg('Breakdown Voltage vs Oil Condition', chartImages.bdvOil);
      addChartImg('Dielectric Strength Comparison', chartImages.strength);
    }

    doc.save('Virtual_Transformer_Oil_BDV_Report.pdf');
  }

  global.ReportExport = {
    exportObservationsCSV,
    exportReportPDF
  };
})(window);
